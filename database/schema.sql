CREATE TABLE IF NOT EXISTS USER (
    userId INTEGER PRIMARY KEY AUTOINCREMENT,
    userName VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    firstName VARCHAR(100) NOT NULL,
    lastName VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL CHECK(role IN ('Admin','Customer'))
);
CREATE TABLE ACCOUNT (
    accountId INTEGER PRIMARY KEY AUTOINCREMENT,
    userId INTEGER NOT NULL REFERENCES USER(userId),
    accountType VARCHAR(100) NOT NULL,
    points INTEGER NOT NULL CHECK(points >= 0)
);
CREATE TABLE IF NOT EXISTS GIFTCARD (
	cardId INTEGER PRIMARY KEY AUTOINCREMENT,
	cardName VARCHAR(100) NOT NULL,
	cardType VARCHAR(100) NOT NULL,
	cardValue REAL NOT NULL,
	points INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS REDEMPTION (
    redeemId INTEGER PRIMARY KEY AUTOINCREMENT,
    date VARCHAR(100) NOT NULL,
    accountId INTEGER NOT NULL REFERENCES ACCOUNT(accountId),
    cardId INTEGER NOT NULL REFERENCES GIFTCARD(cardId),
    pointsRedeemed INTEGER NOT NULL CHECK(pointsRedeemed > 0)
);
